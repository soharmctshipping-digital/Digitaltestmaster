def canon(item, section=''):
    s=str(item or '').lower()
    for g,n,p in CR:
        if p.search(s): return g,n
    s2=(str(section or '')+' '+s).lower()
    for g,n,p in CR:
        if p.search(s2): return g,n
    return 'Unclassified','Unclassified'
